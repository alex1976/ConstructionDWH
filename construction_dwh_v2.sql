/* =========================
   DATE DIMENSION POPULATION
   ========================= */

CREATE PROCEDURE dwh.usp_PopulateDimDate(
    p_start_date DATE,
    p_end_date   DATE
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_start_date IS NULL OR p_end_date IS NULL OR p_end_date < p_start_date THEN
        RAISE EXCEPTION 'Invalid date range for DimDate population.';
    END IF;

    WITH RECURSIVE d AS (
        SELECT p_start_date AS FullDate
        UNION ALL
        SELECT (FullDate + INTERVAL '1 day')::date
        FROM d
        WHERE FullDate < p_end_date
    )
    INSERT INTO dwh.DimDate (
        DateKey,
        FullDate,
        DayNumberOfMonth,
        DayName,
        DayOfWeekISO,
        WeekOfYearISO,
        MonthNumber,
        MonthName,
        QuarterNumber,
        YearNumber,
        YearMonth,
        IsWeekend,
        IsMonthEnd
    )
    SELECT
        to_char(d.FullDate, 'YYYYMMDD')::INTEGER AS DateKey,
        d.FullDate,
        EXTRACT(DAY FROM d.FullDate)::SMALLINT AS DayNumberOfMonth,
        TRIM(to_char(d.FullDate, 'Day')) AS DayName,
        EXTRACT(ISODOW FROM d.FullDate)::SMALLINT AS DayOfWeekISO,
        EXTRACT(WEEK FROM d.FullDate)::SMALLINT AS WeekOfYearISO,
        EXTRACT(MONTH FROM d.FullDate)::SMALLINT AS MonthNumber,
        TRIM(to_char(d.FullDate, 'Month')) AS MonthName,
        EXTRACT(QUARTER FROM d.FullDate)::SMALLINT AS QuarterNumber,
        EXTRACT(YEAR FROM d.FullDate)::SMALLINT AS YearNumber,
        to_char(d.FullDate, 'YYYY-MM') AS YearMonth,
        (EXTRACT(ISODOW FROM d.FullDate) IN (6, 7)) AS IsWeekend,
        (d.FullDate = (date_trunc('month', d.FullDate) + INTERVAL '1 month' - INTERVAL '1 day')::date) AS IsMonthEnd
    FROM d
    WHERE NOT EXISTS (
        SELECT 1
        FROM dwh.DimDate x
        WHERE x.FullDate = d.FullDate
    );
END;
$$;

COMMIT;

