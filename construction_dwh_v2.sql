/*
  ConstructionDWH - Kimball-guided PostgreSQL DDL v2

  Design highlights aligned with Kimball principles:
  - Star schema with conformed dimensions
  - Explicit grain for each fact table
  - Surrogate keys in dimensions (GENERATED BY DEFAULT AS IDENTITY)
  - Type 2 Slowly Changing Dimensions (SCD2) for core entities
  - Unknown member rows (-1) in each dimension
  - Degenerate dimensions in facts (DocumentNumber, LineNumber)
  - BRIN indexes on DateKey for efficient scans on large, date-ordered fact tables

  Notes for large-volume efficiency (Requirement: "handle large volumes of data efficiently"):
  - Consider RANGE partitioning the fact tables by DateKey once volumes justify it
    (PARTITION BY RANGE (DateKey), with per-year/month partitions). Not applied here
    to keep the initial schema simple; the loader can insert into the parent table
    unchanged if partitioning is added later.
  - Consider running ANALYZE/VACUUM maintenance and, for read-heavy analytics,
    evaluate columnar extensions (e.g. Citus/columnar, hydra) if native Postgres
    heap storage becomes a bottleneck.
  - For ML/prediction workloads (Requirement 2), consider optional extensions such as
    plpython3u or pgvector depending on the modeling approach; none are required by
    this schema.
*/

